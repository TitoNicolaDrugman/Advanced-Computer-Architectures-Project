def onnx_to_pytorch(onnx_path: str, output_path: str, dummy_input_shape=(1,3,224,224)):
    # Load & verify ONNX
    model_onnx = onnx.load(onnx_path)
    onnx.checker.check_model(model_onnx)
    print(f"✅ ONNX loaded: {onnx_path}")

    # Convert
    model_pt = ConvertModel(model_onnx)
    model_pt.eval()
    print("✅ Converted to PyTorch nn.Module")

    # Dummy forward-pass (shape check)
    dummy = torch.randn(dummy_input_shape)
    with torch.no_grad():
        _ = model_pt(dummy)
    print(f"✅ Forward OK with dummy input {dummy_input_shape}")

    # Save state_dict
    torch.save(model_pt.state_dict(), output_path)
    print(f"✅ Saved PyTorch state_dict to {output_path}")

