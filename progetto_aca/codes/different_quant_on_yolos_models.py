# 3) Monkey-patch torch.nn.functional.interpolate to handle list-of-tensors scale_factor
import torch
import torch.nn.functional as F
_orig_interpolate = F.interpolate

def _patched_interpolate(input, size=None, scale_factor=None, mode='nearest',
                         align_corners=None, recompute_scale_factor=None, antialias=None):
    # If size is None and scale_factor is list/tuple of Tensors, compute output size
    if size is None and isinstance(scale_factor, (list, tuple)) and \
       all(isinstance(f, torch.Tensor) for f in scale_factor):
        # Convert each tensor factor to float
        factors = [float(f.item()) for f in scale_factor]
        _, _, H, W = input.shape
        new_h = int(H * factors[0])
        new_w = int(W * factors[1])
        size = (new_h, new_w)
        scale_factor = None
    return _orig_interpolate(input, size=size, scale_factor=scale_factor,
                              mode=mode, align_corners=align_corners,
                              recompute_scale_factor=recompute_scale_factor,
                              antialias=antialias)
# Override the original function
F.interpolate = _patched_interpolate

