import onnx
from onnx import shape_inference, helper, TensorProto
import onnxruntime as ort
from onnx2pytorch import ConvertModel

def onnx_to_pytorch_with_patch(onnx_path: str, output_path: str):
    # --- Load the ONNX model ---
    model_onnx = onnx.load(onnx_path)

    # --- Infer shapes ---
    model_onnx = shape_inference.infer_shapes(model_onnx)

    # --- Fix graph outputs: ensure only real outputs are listed ---
    # Use ONNX Runtime to discover actual output names
    sess = ort.InferenceSession(onnx_path, providers=['CPUExecutionProvider'])
    output_names = [o.name for o in sess.get_outputs()]
    # Clear existing outputs and set correct ones
    del model_onnx.graph.output[:]
    for name in output_names:
        # Create a generic FLOAT ValueInfoProto with unknown dims
        vi = helper.make_tensor_value_info(name, TensorProto.FLOAT, None)
        model_onnx.graph.output.append(vi)

    # --- Extract input dimensions (replace unknown with 1) ---
    input_info = model_onnx.graph.input[0].type.tensor_type.shape.dim
    dims = [(d.dim_value if (d.dim_value and d.dim_value > 0) else 1) for d in input_info]
    print(f"Detected input shape: {dims}")

    # --- Convert to PyTorch ---
    pt_model = ConvertModel(model_onnx)
    pt_model.eval()
    print("✅ Converted to PyTorch nn.Module")

    # --- Dummy forward with inferred shape ---
    dummy = torch.randn(*dims)
    with torch.no_grad():
        _ = pt_model(dummy)
    print(f"✅ Dummy forward pass OK with input shape {dims}")

    # --- Save state_dict ---
    torch.save(pt_model.state_dict(), output_path)
    print(f"✅ Saved PyTorch state_dict to {output_path}")


