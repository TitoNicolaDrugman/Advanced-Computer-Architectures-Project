SAVED_MODEL_PATH   = "/content/yolov5nu_wrapped"

# Output path for your fully-quantized TFLite:
OUTPUT_TFLITE_PATH = "/content/model_int8.tflite"

# Folder of COCO train2017 images (mounted Drive):
COCO_IMAGE_DIR     = "/content/drive/MyDrive/train2017"

# Must match your model’s [1, H, W, 3] → here H=W=1024
IMAGE_SIZE         = (192,192)

# Number of calibration samples to run:
NUM_CALIB_SAMPLES  = 300

# I/O dtype: tf.uint8 (zero-point at 0) or tf.int8 (symmetric)
IO_DTYPE           = tf.uint8
# === End of user-configurable section ===

def representative_data_gen():
    """Yields NUM_CALIB_SAMPLES batches of shape (1,H,W,3) for calibration."""
    img_paths = glob.glob(os.path.join(COCO_IMAGE_DIR, "*.jpg")) \
              + glob.glob(os.path.join(COCO_IMAGE_DIR, "*.png"))
    for p in img_paths[:NUM_CALIB_SAMPLES]:
        img = Image.open(p).convert("RGB").resize(IMAGE_SIZE, Image.BILINEAR)
        arr = np.asarray(img, dtype=np.float32) / 255.0            # normalize to [0,1]
        tensor = tf.convert_to_tensor(arr, dtype=tf.float32)
        yield [tf.expand_dims(tensor, axis=0)]                    # shape (1,H,W,3)

# 1. Create the TFLiteConverter
converter = tf.lite.TFLiteConverter.from_saved_model(SAVED_MODEL_PATH)

# 2. Enable full INT8 quantization (weights + activations)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
converter.representative_dataset = representative_data_gen

# 3. Force all ops + I/O to INT8/uint8
converter.target_spec.supported_ops = [
  tf.lite.OpsSet.TFLITE_BUILTINS_INT8,      # int8-only kernels
  tf.lite.OpsSet.SELECT_TF_OPS             # float fallback for everything else
]

converter.inference_input_type  = IO_DTYPE
converter.inference_output_type = IO_DTYPE

# 4. Convert and save
print("Converting to INT8… this may take a few minutes.")
tflite_model = converter.convert()
with open(OUTPUT_TFLITE_PATH, "wb") as f:
    f.write(tflite_model)
print("✅ Fully-quantized TFLite model saved to", OUTPUT_TFLITE_PATH)

import tensorflow as tf

base = tf.saved_model.load("/content/yolov5nu_saved_model")
infer = base.signatures["serving_default"]

# structured_input_signature = (args, kwargs)
_, kwargs = infer.structured_input_signature

# build a list of TensorSpecs from the kwargs dict
input_specs = [
    tf.TensorSpec(spec.shape, spec.dtype, name=name)
    for name, spec in kwargs.items()
]

class WrapModel(tf.Module):
    def __init__(self, fn):
        super().__init__()
        self.fn = fn

    @tf.function(input_signature=input_specs)
    def __call__(self, *args, **kwargs):
        # unpack exactly like the original
        out = self.fn(*args, **kwargs)
        if isinstance(out, dict):
            key = next(iter(out))
            y = out[key]
        else:
            y = out
        return tf.transpose(y, perm=[0,2,1])

wrapped = WrapModel(infer)
tf.saved_model.save(wrapped, "/content/yolov5nu_wrapped")

