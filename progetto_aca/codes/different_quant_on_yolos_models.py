class CalibReader(CalibrationDataReader):
    def __init__(self, folder, input_name):
        self.files = list(Path(folder).glob("*"))
        self.input = input_name
        self.i = 0
    def get_next(self):
        if self.i >= len(self.files):
            return None
        img = cv2.cvtColor(cv2.imread(str(self.files[self.i])), cv2.COLOR_BGR2RGB)
        img = cv2.resize(img, (IMG_SIZE, IMG_SIZE)).astype(np.float32) / 255.
        img = np.transpose(img, (2,0,1))[None]
        self.i += 1
        return {self.input: img}

