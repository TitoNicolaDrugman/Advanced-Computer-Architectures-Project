# ─── Patch the single Add node that has 32 vs 16 channels ────────────────────
model = onnx.load(str(ONNX_PATH))
graph = model.graph

# Locate the specific Add by its exact name
target = "wa/model.2/m.0/Add"
for node in graph.node:
    if node.name == target and node.op_type == "Add":
        a, b = node.input  # a has C=32, b has C=16

        # Pull out the channel dims from the inferred shape info
        c0 = c1 = None
        for vi in graph.value_info:
            if vi.name == a:
                c0 = vi.type.tensor_type.shape.dim[1].dim_value
            if vi.name == b:
                c1 = vi.type.tensor_type.shape.dim[1].dim_value
        assert c0 is not None and c1 is not None, "Shape info missing"

        diff = int(c0 - c1)  # should be 16
        # Create a pads initializer: [N_beg,C_beg,H_beg,W_beg, N_end,C_end,H_end,W_end]
        pads = np.array([0,0,0,0, 0,diff,0,0], dtype=np.int64)
        pads_name = f"{b}_pads"
        graph.initializer.append(
            numpy_helper.from_array(pads, name=pads_name)
        )

        # Insert a Pad node on the smaller-C branch
        padded = f"{b}_padded"
        pad_node = helper.make_node(
            "Pad",
            inputs=[b, pads_name],
            outputs=[padded],
            name=f"{b}_pad",
            mode="constant"
        )
        idx = list(graph.node).index(node)
        graph.node.insert(idx, pad_node)

        # Reroute the Add to use the padded tensor
        node.input[1] = padded
        break

